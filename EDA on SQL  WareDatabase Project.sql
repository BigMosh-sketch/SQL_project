/*Group customers into three segment based on their spending behaviour:
Vip: at least 12 month of history and spending more than $5000
Regular: at least 12 month of history but spending $5000 or less
New:lifespan less 12 month
and the total number of customer by each group*/
With customers_segment as (
Select
	c.customer_key,
	sum(f.sales) as total_sales,
	min(f.order_date) as first_date,
	max(f.order_date) as last_date,
	datediff(month,min(f.order_date),max(f.order_date)) as life_span
from gold.fact_sales f left join gold.dim_customers c
on f.customer_key = c.customer_key
group by c.customer_key)

Select 
	Spending_behaviour,
	count(customer_key) as total_customer
from
(Select 
	customer_key,
	case	
		when life_span >= 12 and total_sales > 5000 then 'VIP'
		when life_span >= 12 and total_sales <= 5000 then 'Regular'
		else'New'
	End as Spending_behaviour
from customers_segment)t
group by Spending_behaviour
order by total_customer desc
/*
============================================================================================================================
Customers report

============================================================================================================================
purpose:
	This report consolidate key customers metrics and behaviour

Highligth:
	1. Gather important field such names, age and transactional details
	2.Segment customers into categories (VIP, Regular and New) and Age group
	3.Aggregate customers level metrics:
		- total orders
		- total sales
		- total product 
		- total quantity purchased
	Calculate Valuable KPIs:
		- recency (since last order)
		- average order value
		- average monthly spend

============================================================================================================================
*/
Create or alter view gold.customers_table as 
with base_query as (
Select 
--===========================================================================================================================
--Purpose: to retrieve core table column

--==========================================================================================================================
	f.order_number,
	f.product_key,
	f.order_date,
	f.sales,
	f.quantity,
	c.customer_key,
	c.customer_number,
	concat(c.firstname,' ', c.lastname) as fullname,
	c.DOB,
	datediff(year,c.DOB,getdate()) as customer_age
from gold.fact_sales f left join gold.dim_Customers c
on f.customer_key = c.customer_key 
where order_date is not null)

, customer_agggregate as (

Select 
	customer_key,
	customer_number,
	fullname,
	customer_age,															--Customer_aggregate
	count(distinct Order_number) as total_order,
	count(distinct product_key) as total_product,
	sum(sales) as total_sales,
	sum(quantity) as total_quantity_purchased,
	max(order_date) as last_date,
	min(order_date) as first_date,
	datediff(month,min(order_date),max(order_date)) as life_span
from base_query
group by customer_key,customer_number,fullname,customer_age)

Select 
	customer_key,
	customer_number,
	fullname,
	customer_age,
	case
		when customer_age < 20 then 'Below 20'
		when customer_age between 20 and 29 then '20 - 29'
		when customer_age between 30 and 39 then '30 - 39'
		when customer_age between 40 and 49 then '40 - 49'
		else 'Above 50'
	end as age_group,
	total_order,
	total_product,
	total_quantity_purchased,
	total_sales,
	life_span,
	case
		when life_span >= 12 and total_sales > 5000  then 'VIP'
		when life_span >= 12 and total_sales <= 5000 then 'Regular'
		else 'New'
	end as customer_badge,
	last_date,
	datediff(month,last_date,getdate()) as recency,
	case 
		when total_order = 0 then total_sales
		else total_sales/total_order 
	end as average_order_value,
	case
		when life_span = 0 then total_sales
		else total_sales/life_span 
	end as average_monthly_spend
from customer_agggregate 
	
