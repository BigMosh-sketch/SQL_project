---Performance Analysis

-- Analyze the year performance of products by comparing each product's sales to both
--its  Average sales performance and the previous year sales

with Yearly_Product_performance as(
Select  
	year(f.order_date) as order_date,
	p.product_name as product_name, 
	sum(f.sales) as current_sales 
	from gold.fact_sales f left join gold.dim_products p
on f.product_key = p.product_key
where f.order_date is not null
group by p.product_name,year(f.order_date))

Select 
	order_date,
	product_name,
	current_sales,
	Avg(current_sales) over(partition by product_name) as Average_Sales,
	current_sales - Avg(current_sales) over(partition by product_name) as diff_avg,
	case
		when current_sales - Avg(current_sales) over(partition by product_name) > 0 then 'Above Average'
		when current_sales - Avg(current_sales) over(partition by product_name) < 0 then 'Below Average'
		Else 'Average'
	End as Average_diff,
	lag(current_sales) over(partition by product_name order by order_date) as pervious_sales,
	current_sales - 	lag(current_sales) over(partition by product_name order by order_date) as YoY_change
from Yearly_Product_performance
order by product_name, order_date
	

